import sys
sys.path.insert(0, "src")
from usv.auto_annotation.postprocess.overlap_resolver import _bboxes_overlap

# 1. Явное перекрытие (50% площади) — должно быть True
assert _bboxes_overlap((0, 0, 100, 100), (50, 50, 150, 150)) is True, "FAIL: явное перекрытие"

# 2. Полное поглощение — должно быть True
assert _bboxes_overlap((0, 0, 200, 200), (50, 50, 100, 100)) is True, "FAIL: поглощение"

# 3. Боксы рядом, без перекрытия — должно быть False
assert _bboxes_overlap((0, 0, 100, 100), (101, 0, 200, 100)) is False, "FAIL: соседние боксы"

# 4. Касание 1 пикселем (граница) — КЛЮЧЕВОЙ ТЕСТ
# Старый код → True (баг), новый код → False (правильно)
assert _bboxes_overlap((0, 0, 100, 100), (99, 0, 200, 100)) is False, \
    "FAIL: касание 1px — IoU слишком мал, не должно считаться конфликтом"

# 5. Небольшое перекрытие (2% площади) — ниже порога 0.05, должно быть False
# bbox A: 100x100, bbox B: 100x100, пересечение 10x10 = 100px
# IoU = 100 / (10000 + 10000 - 100) = 100/19900 ≈ 0.005 < 0.05
assert _bboxes_overlap((0, 0, 100, 100), (90, 90, 190, 190)) is False, \
    "FAIL: перекрытие 1% — ниже порога IoU"

# 6. Значительное перекрытие (25% площади) — должно быть True
# bbox A: 100x100, bbox B: 100x100, пересечение 50x50 = 2500px
# IoU = 2500 / (10000 + 10000 - 2500) = 2500/17500 ≈ 0.143 > 0.05
assert _bboxes_overlap((0, 0, 100, 100), (50, 50, 150, 150)) is True, \
    "FAIL: перекрытие 25% — выше порога IoU"

# 7. Полностью не пересекаются — должно быть False
assert _bboxes_overlap((0, 0, 50, 50), (100, 100, 200, 200)) is False, "FAIL: нет пересечения"

print("✅ Все тесты прошли успешно!")